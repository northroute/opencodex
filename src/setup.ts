/** Template for the gateway .env file. Keep in sync with .env.example (tested). */
export const ENV_TEMPLATE = `# OpenCodex gateway secrets. Keep this file private (mode 0600).
# Values are loaded by the gateway at startup and are NOT passed to the Codex agent.

# Telegram bot token from @BotFather, e.g. 123456789:AA...
TELEGRAM_BOT_TOKEN=

# The only Telegram group the bot answers in (negative id, e.g. -1001234567890).
TELEGRAM_CHAT_ID=
`;

export interface SetupOptions {
  configPath: string;
  /** Repository root containing dist/index.js. */
  repoRoot: string;
  /** Node binary for the launcher (default: first `node` on PATH, else this process). */
  nodePath?: string;
  botName?: string;
  codexBinary?: string;
}

export interface SetupReport {
  created: string[];
  kept: string[];
  fixed: string[];
  warnings: string[];
  launcherPath: string;
  /** Names (never values) of required variables still empty in .env. */
  emptyVars: string[];
}

/** Safe-by-default profile for a single allowlisted Telegram group (TOUDEVS-107). */
export function buildProfileConfig(opts: { dataDir: string; botName: string; codexBinary: string }): string {
  return `# OpenCodex configuration generated by \`opencodex setup\`.
# Secrets come from the .env file next to this config; do not paste them here.

gateway:
  port: 18790
  dataDir: ${JSON.stringify(opts.dataDir)}
  logLevel: "info"
  logFormat: "json"

engine:
  type: "codex"
  maxProcesses: 1
  idleTimeoutMs: 600000
  codex:
    binary: ${JSON.stringify(opts.codexBinary)}
    sandbox: "read-only"
    approvalPolicy: "never"
    extraArgs: []

auth:
  defaultPolicy: "pairing"

bots:
  - name: ${JSON.stringify(opts.botName)}
    token: "\${TELEGRAM_BOT_TOKEN}"
    auth:
      dmPolicy: "disabled"
      groupPolicy: "allowlist"
      allowFrom: []
      groups:
        "\${TELEGRAM_CHAT_ID}":
          enabled: true
`;
}

/** First executable named `name` on PATH, or undefined. */
export function findOnPath(name: string, pathEnv = process.env.PATH ?? ""): string | undefined {
  for (const dir of pathEnv.split(delimiter)) {
    if (!dir) continue;
    const candidate = join(dir, name);
    try {
      accessSync(candidate, constants.X_OK);
      return candidate;
    } catch {
      // not here
    }
  }
  return undefined;
}

function shQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

export function buildLauncher(nodePath: string, repoRoot: string): string {
  return `#!/bin/sh
# Generated by \`opencodex setup\`. Re-run setup if the checkout or Node moves.
exec ${shQuote(nodePath)} ${shQuote(join(repoRoot, "dist", "index.js"))} "$@"
`;
}

function mode(path: string): number {
  return statSync(path).mode & 0o777;
}

/** Tighten permissions if group/other bits are set; returns true if changed. */
function tighten(path: string, wanted: number): boolean {
  if ((mode(path) & 0o077) === 0) return false;
  chmodSync(path, wanted);
  return true;
}

function displayDataDir(dir: string): string {
  const home = process.env.HOME;
  if (home && (dir === home || dir.startsWith(home + "/"))) {
    return "~" + dir.slice(home.length);
  }
  return dir;
}

/** Read gateway.dataDir from an existing config without expanding ${VAR}s. */
function rawDataDir(configPath: string): string | undefined {
  try {
    const doc = parseDocument(readFileSync(configPath, "utf-8"));
    const value = doc.getIn(["gateway", "dataDir"]);
    if (typeof value !== "string") return undefined;
    return resolve(value.replace(/^~/, process.env.HOME ?? ""));
  } catch {
    return undefined;
  }
}

/**
 * Idempotent setup. Creates missing files with private permissions and never
 * overwrites existing config.yaml, .env or a launcher with different content.
 */
export function runSetup(opts: SetupOptions): SetupReport {
  const report: SetupReport = {
    created: [],
    kept: [],
    fixed: [],
    warnings: [],
    launcherPath: "",
    emptyVars: [],
  };
  const configPath = resolve(opts.configPath);
  const configDir = dirname(configPath);

  if (!existsSync(configDir)) {
    mkdirSync(configDir, { recursive: true, mode: 0o700 });
    report.created.push(configDir);
  } else if (tighten(configDir, 0o700)) {
    report.fixed.push(`${configDir} -> 0700`);
  }

  // config.yaml
  if (!existsSync(configPath)) {
    const codexBinary = opts.codexBinary ?? "codex";
    writeFileSync(
      configPath,
      buildProfileConfig({
        dataDir: displayDataDir(configDir),
        botName: opts.botName ?? "plane-agent",
        codexBinary,
      }),
      { mode: 0o600 },
    );
    report.created.push(configPath);
  } else {
    report.kept.push(configPath);
    const content = readFileSync(configPath, "utf-8");
    if (content.includes("codex-sanitized")) {
      report.warnings.push(
        "config.yaml uses the codex-sanitized wrapper; it is no longer needed " +
        "(the gateway withholds .env variables from Codex itself). Set engine.codex.binary to \"codex\" when convenient.",
      );
    }
  }

  // .env
  const envPath = envFilePath(configPath);
  if (!existsSync(envPath)) {
    writeFileSync(envPath, ENV_TEMPLATE, { mode: 0o600 });
    report.created.push(envPath);
  } else {
    report.kept.push(envPath);
    if (tighten(envPath, 0o600)) report.fixed.push(`${envPath} -> 0600`);
  }
  const envValues = parseEnv(readFileSync(envPath, "utf-8"));
  report.emptyVars = ["TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID"].filter(
    (name) => !envValues[name] && !process.env[name],
  );

  // Private runtime directories (data dir may differ from the config dir).
  const dataDir = rawDataDir(configPath) ?? configDir;
  for (const dir of [dataDir, join(dataDir, "logs"), join(dataDir, "messages")]) {
    if (existsSync(dir) && tighten(dir, 0o700)) report.fixed.push(`${dir} -> 0700`);
  }

  // Launcher
  const binDir = join(configDir, "bin");
  mkdirSync(binDir, { recursive: true, mode: 0o700 });
  const launcherPath = join(binDir, "opencodex");
  report.launcherPath = launcherPath;
  const nodePath = opts.nodePath ?? findOnPath("node") ?? process.execPath;
  const launcher = buildLauncher(nodePath, resolve(opts.repoRoot));
  if (!existsSync(launcherPath)) {
    writeFileSync(launcherPath, launcher, { mode: 0o700 });
    report.created.push(launcherPath);
  } else if (readFileSync(launcherPath, "utf-8") === launcher) {
    report.kept.push(launcherPath);
  } else {
    report.warnings.push(
      `${launcherPath} exists with different content and was not overwritten. ` +
      "Remove it and re-run setup to use this checkout.",
    );
  }

  return report;
}

// --- doctor ---

export type CheckStatus = "PASS" | "WARN" | "FAIL" | "SKIP";

export interface CheckResult {
  name: string;
  status: CheckStatus;
  detail: string;
}

export interface DoctorOptions {
  configPath: string;
  mcpName?: string;
  /** Override for tests: contents of /proc/net/tcp and /proc/net/tcp6. */
  procNetTcp?: string[];
}

function isLoopbackHex(addr: string): boolean {
  if (addr.length === 8) {
    // IPv4, little-endian: 0100007F = 127.0.0.1
    return addr.slice(6, 8).toUpperCase() === "7F";
  }
  const a = addr.toUpperCase();
  if (a === "00000000000000000000000001000000") return true; // ::1
  // ::ffff:127.x.x.x
  return a.startsWith("0000000000000000FFFF0000") && a.slice(30, 32) === "7F";
}

/** Local addresses listening on `port`, as raw hex from /proc/net/tcp{,6}. */
export function listeningAddresses(port: number, tables: string[]): string[] {
  const portHex = port.toString(16).toUpperCase().padStart(4, "0");
  const result: string[] = [];
  for (const table of tables) {
    for (const line of table.split("\n").slice(1)) {
      const cols = line.trim().split(/\s+/);
      if (cols.length < 4) continue;
      const [addr, p] = cols[1].split(":");
      if (p?.toUpperCase() === portHex && cols[3] === "0A") result.push(addr);
    }
  }
  return result;
}

function readProcNetTcp(): string[] | undefined {
  const tables: string[] = [];
  for (const path of ["/proc/net/tcp", "/proc/net/tcp6"]) {
    try {
      tables.push(readFileSync(path, "utf-8"));
    } catch {
      // not available
    }
  }
  return tables.length > 0 ? tables : undefined;
}

function privateMode(path: string, wanted: number, label: string): CheckResult {
  if (!existsSync(path)) return { name: label, status: "FAIL", detail: `${path} is missing (run setup)` };
  const m = mode(path);
  return (m & 0o077) === 0
    ? { name: label, status: "PASS", detail: `${path} ${m.toString(8)}` }
    : { name: label, status: "FAIL", detail: `${path} is ${m.toString(8)}, expected ${wanted.toString(8)}` };
}

/** Read-only self-check. Never prints secret values. */
export function runDoctor(opts: DoctorOptions): CheckResult[] {
  const results: CheckResult[] = [];
  const configPath = resolve(opts.configPath);
  const mcpName = opts.mcpName ?? "tou-plane";

  const major = Number(process.versions.node.split(".")[0]);
  results.push({
    name: "node",
    status: major >= 22 ? "PASS" : "FAIL",
    detail: `v${process.versions.node} (need >= 22)`,
  });

  if (!existsSync(configPath)) {
    results.push({ name: "config", status: "FAIL", detail: `${configPath} is missing (run setup)` });
    return results;
  }

  const envPath = envFilePath(configPath);
  results.push(privateMode(envPath, 0o600, "env file permissions"));

  const rawConfig = readFileSync(configPath, "utf-8");
  const missing = missingEnvVars(rawConfig);
  results.push(
    missing.length === 0
      ? { name: "required variables", status: "PASS", detail: "all ${VAR} references are set" }
      : { name: "required variables", status: "FAIL", detail: `empty or unset: ${missing.join(", ")}` },
  );

  let config;
  try {
    config = loadConfig(configPath);
    results.push({ name: "config", status: "PASS", detail: configPath });
  } catch (err) {
    results.push({ name: "config", status: "FAIL", detail: (err as Error).message.split("\n")[0] });
  }

  const dataDir = config ? resolveDataDir(config) : dirname(configPath);
  results.push(privateMode(dataDir, 0o700, "data dir permissions"));

  if (config) {
    const bots = (() => {
      try {
        return resolveBots(config);
      } catch {
        return [];
      }
    })();
    const open = bots.filter((b) => b.dmPolicy !== "disabled" || b.groupPolicy !== "allowlist"
      || Object.keys(b.groups).length === 0);
    results.push(
      bots.length === 0
        ? { name: "telegram allowlist", status: "FAIL", detail: "no bots configured" }
        : open.length === 0
          ? { name: "telegram allowlist", status: "PASS", detail: "DM disabled, groups allowlisted" }
          : { name: "telegram allowlist", status: "WARN", detail: `not allowlist-only: ${open.map((b) => b.name).join(", ")}` },
    );
  }

  const binary = config?.engine.codex.binary ?? "codex";
  const childEnv = buildChildEnv();
  const version = spawnSync(binary, ["--version"], { stdio: "pipe", timeout: 10000, env: childEnv });
  const codexOk = !version.error && version.status === 0;
  results.push(
    codexOk
      ? { name: "codex binary", status: "PASS", detail: `${binary}: ${version.stdout.toString().trim()}` }
      : { name: "codex binary", status: "FAIL", detail: `"${binary}" not runnable` },
  );

  if (codexOk) {
    const login = spawnSync(binary, ["login", "status"], { stdio: "pipe", timeout: 15000, env: childEnv });
    results.push(
      login.status === 0
        ? { name: "codex login", status: "PASS", detail: "logged in" }
        : { name: "codex login", status: "FAIL", detail: "not logged in (run: codex login)" },
    );

    const mcp = spawnSync(binary, ["mcp", "list"], { stdio: "pipe", timeout: 15000, env: childEnv });
    const listed = mcp.status === 0
      && mcp.stdout.toString().split("\n").some((line) => line.trim().split(/\s+/)[0] === mcpName);
    results.push(
      listed
        ? { name: "codex mcp", status: "PASS", detail: `${mcpName} is configured` }
        : { name: "codex mcp", status: "FAIL", detail: `${mcpName} not found in \`codex mcp list\`` },
    );
  } else {
    results.push({ name: "codex login", status: "SKIP", detail: "codex binary not runnable" });
    results.push({ name: "codex mcp", status: "SKIP", detail: "codex binary not runnable" });
  }

  const leaked = withheldEnvKeys().filter((key) => childEnv[key] !== undefined);
  results.push(
    leaked.length === 0
      ? { name: "agent environment", status: "PASS", detail: `withheld from Codex: ${withheldEnvKeys().join(", ")}` }
      : { name: "agent environment", status: "FAIL", detail: `visible to Codex: ${leaked.join(", ")}` },
  );

  const tables = opts.procNetTcp ?? readProcNetTcp();
  if (!config) {
    // Without a loaded config the port is unknown; a default could match another gateway.
    results.push({ name: "api bind", status: "SKIP", detail: "config not loaded" });
  } else if (!tables) {
    results.push({ name: "api bind", status: "SKIP", detail: "/proc/net/tcp unavailable" });
  } else {
    const port = config.gateway.port;
    const addrs = listeningAddresses(port, tables);
    const exposed = addrs.filter((a) => !isLoopbackHex(a));
    results.push(
      addrs.length === 0
        ? { name: "api bind", status: "SKIP", detail: `nothing listening on port ${port} (gateway not running)` }
        : exposed.length === 0
          ? { name: "api bind", status: "PASS", detail: `port ${port} on loopback only` }
          : { name: "api bind", status: "FAIL", detail: `port ${port} listens on a non-loopback address` },
    );
  }

  return results;
}
